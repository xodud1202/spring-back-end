-- Apply to the schema used by existing /api/work endpoints before deployment.
CREATE TABLE IF NOT EXISTS WORK_READING_RECORD (
    ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    WORK_USER_NO BIGINT NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    AUTHOR VARCHAR(200) NOT NULL,
    TRANSLATOR VARCHAR(200),
    STARTED_ON DATE,
    COMPLETED_ON DATE,
    CONTENT VARCHAR(200),
    RATING DECIMAL(2,1),
    NOTES VARCHAR(4000),
    INDEX IDX_WORK_READING_RECORD_OWNER (WORK_USER_NO, ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;